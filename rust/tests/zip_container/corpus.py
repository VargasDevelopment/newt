def archive(items, comment=b'', prefix=b'', directory_extra=b''):
    body = bytearray(prefix)
    central = bytearray()
    for name, data, method, local_extra, central_extra, entry_comment in items:
        if method == 8:
            encoder = zlib.compressobj(6, zlib.DEFLATED, -15)
            payload = encoder.compress(data) + encoder.flush()
        else:
            payload = data
        offset = len(body)
        crc = zlib.crc32(data)
        body += struct.pack('<IHHHHHIIIHH', 0x04034b50, 20, 0, method, 0, 0,
                            crc, len(payload), len(data), len(name), len(local_extra))
        body += name + local_extra + payload
        central += struct.pack('<IHHHHHHIIIHHHHHII', 0x02014b50, 20, 20, 0, method,
                               0, 0, crc, len(payload), len(data), len(name),
                               len(central_extra), len(entry_comment), 0, 0, 0, offset)
        central += name + central_extra + entry_comment
    off = len(body)
    body += central + directory_extra
    body += struct.pack('<IHHHHIIH', 0x06054b50, 0, 0, len(items), len(items),
                        len(central), off, len(comment)) + comment
    return bytes(body), off


def item(name=b'a', data=b'alpha', method=0, local=b'', extra=b'', comment=b''):
    return name, data, method, local, extra, comment


