fn glyph(code: u8) -> Option<&'static [u8; 7]> {
    if code == b' ' { return None; }
    GLYPHS.iter().find(|(found, _)| *found == code)
        .or_else(|| GLYPHS.iter().find(|(found, _)| *found == b'?'))
        .map(|(_, rows)| rows)
}
fn left_edge(rows: &[u8; 7]) -> i32 {
    let bits = rows.iter().copied().fold(0u8, |bits, row| bits | row);
    (0..5).find(|&column| bits & (16u8 >> column) != 0).unwrap_or(0)
}
fn advance(code: u8) -> i32 {
    if code == b' ' { return 3; }
    let Some(rows) = glyph(code) else { return 6; };
    let bits = rows.iter().copied().fold(0u8, |bits, row| bits | row);
    let mut right = 4;
    while right > 0 && bits & (16 >> right) == 0 { right -= 1; }
    right - left_edge(rows) + 2
}
pub(super) fn width(value: &[u8], scale: i32) -> i32 {
    let width: i32 = value.iter().take(128).take_while(|&&code| code != 0)
        .map(|&code| advance(code) * scale).sum();
    if width > 0 { width - scale } else { 0 }
}
pub(super) fn text(c: &mut UiCanvas<'_>, mut x: i32, y: i32, value: &[u8], scale: i32) {
    for &code in value.iter().take(128).take_while(|&&code| code != 0) {
        if let Some(rows) = glyph(code) {
            let left = left_edge(rows);
            for (row, &bits) in rows.iter().enumerate() {
                for column in left..5 {
                    if bits & (16 >> column) != 0 {
                        c.rect(x + (column - left) * scale, y + row as i32 * scale, scale, scale, true);
                    }
                }
            }
        }
        x += advance(code) * scale;
    }
}
