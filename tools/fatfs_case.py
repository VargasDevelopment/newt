def _upper(code):
    # FatFs maps BMP code units only; surrogate units are unchanged too.
    if code >= 0x10000:
        return code
    table = CVT1 if code < 0x1000 else CVT2
    index = 0
    while True:
        base = table[index]
        index += 1
        if base == 0 or code < base:
            return code
        command, count = table[index] >> 8, table[index] & 255
        index += 1
        if code < base + count:
            if command == 0:
                return table[index + code - base]
            if command == 1:
                return code - ((code - base) & 1)
            return code + {2: -16, 3: -32, 4: -48, 5: -26, 6: 8, 7: -80, 8: -0x1c60}[command]
        if command == 0:
            index += count


def name_key(name):
    """One-code-point uppercase, without Python's expansions or normalization."""
    return tuple(_upper(ord(char)) for char in name)
